void HandleMSBuildOutput(std::string line)
{
	// --- 1. Trim newline ---
	if (!line.empty() && (line.back() == '\n' || line.back() == '\r'))
		line.pop_back();
	if (line.size() > 2000) { LOGE("word count exceeded console buffer size!!"); return; }
	// --- 2. Determine log level ---
	Logger::LogLevel level = Logger::LogLevel::Info;

	// make a lowercase copy for comparison
	std::string lower = line;
	std::transform(lower.begin(), lower.end(), lower.begin(), ::tolower);

	// MSBuild typically includes "error" or "warning" in the line
	if (lower.find("error(s)") != std::string::npos && lower.find("0 error(s)") == std::string::npos)
		CEO::Instance().GetManager<ResourceManager>()->GetAudio("faaah.mp3").Play();

	if (lower.find("error") != std::string::npos)
		level = Logger::LogLevel::Error;
	else if (lower.find("warning") != std::string::npos)
		level = Logger::LogLevel::Warning;

	// --- 3. Send to logger (which stacks duplicates automatically) ---
	CEO::Instance().GetManager<Logger>()->AddLog(line, level);
}


