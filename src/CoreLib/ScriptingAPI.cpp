/*!
* \brief
*   Dynamically loads the compiled Scripts.dll and initializes all
*   native script components defined within.
* \param
*   registry - ECS registry instance
* \param
*   componentRegistry - global component registry
* \param
*   typeMap - reflection type map for runtime type registration
* \param
*   input - input system instance
* \param
*   ss - pointer to savestate instance
*/
void LoadScript(Registry& registry, ComponentRegistry& componentRegistry,
	std::unordered_map<std::string, rtr::TypeInfo>* typeMap, Input* input, CEO* ceo)
{

	hDll = LoadLibraryA("Scripts.dll");
	if (!hDll)
	{
		std::cerr << "Failed to load DLL bruh\n";
		return;
	}

	using NativeComponentInitialise = void(*)(Registry&, ComponentRegistry&, std::unordered_map<std::string, rtr::TypeInfo>*
		, Input* input, CEO*);
	NativeComponentInitialise ProcessData = reinterpret_cast<NativeComponentInitialise>(
		GetProcAddress(hDll, "NativeComponentInitialise")
		);
	if (!ProcessData)
	{
		std::cerr << "Failed to locate initialise function!" << std::endl;
		FreeLibrary(hDll);
		return;
	}
	ProcessData(registry, componentRegistry, typeMap, input, ceo);
}

/*!
* \brief
*   Frees all entities and unloads the currently loaded Scripts.dll
*   from memory.
* \param
*   registry - ECS registry
* \param
*   componentRegistry - global component registry
*/
void FreeScript(Registry& registry, ComponentRegistry& componentRegistry)
{

	DeleteScriptInstance(registry, componentRegistry);


	using NativeComponentDestroy = void(*)(Registry&, ComponentRegistry&);
	NativeComponentDestroy NativeComponentClear = reinterpret_cast<NativeComponentDestroy>(
		GetProcAddress(hDll, "NativeComponentClear")
		);

	if (!NativeComponentClear)
	{
		std::cerr << "Failed to locate clear function!" << std::endl;
		FreeLibrary(hDll);
		return;
	}
	NativeComponentClear(registry, componentRegistry);


	if (!FreeLibrary(hDll)) {
		DWORD err = GetLastError();
		std::cerr << "FreeLibrary failed. Error code: " << err << std::endl;
	}
	else {
		std::cout << "DLL unloaded successfully." << std::endl;
	}



}



