/*!
* \brief
*   Scans the specified directory for header files defining script classes that
*   inherit from ScriptInstance. Extracts class names and UPROPERTY fields.
* \param
*   directoryPath - path to search for C++ script header files
*/
void ScanDirectoryForClasses(const char* directoryPath)
{

	std::regex classRegex(R"(class\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*:\s*public\s+ScriptInstance)");
	std::regex propertyREGEX(R"(UPROPERTY)");


	std::vector<std::pair<std::string, std::vector<std::string>>> ClassesAndProperties;
	std::vector<std::string> classdirVec;
	for (const auto& entry : std::filesystem::recursive_directory_iterator(directoryPath))
	{
		if (entry.is_regular_file() && entry.path().extension() == ".h")
		{
			std::ifstream file(entry.path());
			std::string line;

			if (!file.is_open()) {
				std::cerr << "Failed to open: " << entry.path() << std::endl;
				continue;
			}
			std::cout << "Opened: " << entry.path() << std::endl;
			std::vector<std::string>Properties;
			std::string className;
			std::string classDir;

			while (std::getline(file, line))
			{
				std::smatch propmatch;

				if (std::regex_search(line, propmatch, propertyREGEX) && !className.empty())
				{
					std::cout << "found UPROPERTY" << std::endl;
					std::string nextLine;
					if (std::getline(file, nextLine))
					{
						// Optional: strip leading/trailing whitespace
						std::istringstream iss(nextLine);
						std::string name;
						//skips first word
						iss >> name;

						iss >> name;
						std::cout << "found type:" << name << std::endl;
						name.erase(std::remove(name.begin(), name.end(), ';'), name.end());
						Properties.push_back(name);

					}
				}
				std::smatch match;
				if (std::regex_search(line, match, classRegex))
				{
					// Extract class name from regex match className = match[1];
					std::cout << "Found class: " << className << " in " << entry.path() << "\n";
					className = match[1];
					classDir = entry.path().string();
					
					// Generate code for the class (this part can use RTTR or your own logic)
				}


			}
			if (!className.empty())
			{
				ClassesAndProperties.emplace_back(std::make_pair(className, Properties));
				std::filesystem::create_directory("Assets/Scripts/");
				std::string Assets = "Assets/Scripts/" + className + ".Script";
				std::ofstream ofs(Assets);



				classdirVec.emplace_back(classDir);
				className.clear();
				classDir.clear();
			}
		}
	}

	generateCodeForClass(ClassesAndProperties, classdirVec);

}


