/*!
* \brief
*   Updates all active native scripts each frame by invoking their OnUpdate
*   or OnStart callbacks as needed.
* \param
*   registry - ECS registry
* \param
*   componentRegistry - global component registry
* \param
*   dt - frame delta time
* \param
*   firstframe - flag indicating first frame of execution
*/
void UpdateScriptInstance(Registry& registry, ComponentRegistry& , float dt, bool& firstframe)
{
	auto entities = registry.GetEntitiesWithComponents<NativeScriptingComponent>();

	UpdateStackManager* usm = CEO::Get<UpdateStackManager>();
	for (auto ent : entities)
	{
		if (usm->ShouldNotUpdate(ent)) continue;
		if (!usm->IsActive(ent)) continue;

		NativeScriptingComponent& Native = *registry.GetComponent<NativeScriptingComponent>(ent);
		for (auto& [name, Instance] : Native.scripts)
		{
			if (Instance.isStarted)
			{
				if (Instance.state == NativeScriptingComponent::ScriptState::Faulted)
				{
					LOGE("Error in %s OnUpdate(): ", name.c_str());
					continue;
				}
				Instance.BindFrom(Instance.Instance);
				OnUpdateCall_Safe(&Instance, &registry, dt, &firstframe);
				Instance.BindTo(Instance.Instance);
			}
		}
		firstframe = false;

	}
}

/*!
* \brief
*   Deletes all existing script instances and clears registered scripts
*   from all NativeScriptingComponents.
* \param
*   registry - ECS registry
* \param
*   componentRegistry - global component registry
*/
void DeleteScriptInstance(Registry& registry, ComponentRegistry&)
{
	auto entities = registry.GetEntitiesWithComponents<NativeScriptingComponent>();
	for (auto ent : entities)
	{
		auto Native = registry.GetComponent<NativeScriptingComponent>(ent);
		for (auto& [name, Instance] : Native->scripts)
		{
			if (Instance.Instance)
			{
				Instance.OnDeleteScript(Instance);
			}
		}
	}

}
